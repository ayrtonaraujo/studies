# maiuscula, minúscula e título
titulo = "Python"

print(titulo.upper())
print(titulo.lower())
print(titulo.title())

print()

# eliminar espaços em branco
titulo2 = "   Python  "
print(titulo2.strip())
print(titulo2.rstrip())
print(titulo2.lstrip())

print()


# junções e centralização
print(titulo.center(12, "#"))
print(".".join(titulo))

print()


